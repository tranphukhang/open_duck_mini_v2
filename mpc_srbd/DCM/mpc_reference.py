DEFAULT_GRAVITY = 9.81


# ============================================================
# VALIDATION
# ============================================================

def _validate_vector(
    value,
    name,
    size
):
    value = np.asarray(
        value,
        dtype=float
    ).reshape(-1)


    if value.shape != (
        size,
    ):

        raise ValueError(
            f"{name} phải có shape ({size},), "
            f"nhưng nhận được {value.shape}."
        )


    if not np.all(
        np.isfinite(
            value
        )
    ):

        raise ValueError(
            f"{name} chứa NaN hoặc Inf."
        )


    return value


def _validate_positive_scalar(
    value,
    name
):
    value = float(
        value
    )


    if (
        not np.isfinite(
            value
        )
        or
        value <= 0.0
    ):

        raise ValueError(
            f"{name} phải hữu hạn và > 0."
        )


    return value


# ============================================================
# BUILD TRANSLATIONAL MPC REFERENCE
#
# This module is only a wrapper around:
#
#     dcm_reference_horizon.py
#
# and:
#
#     com_reference_from_dcm.py
#
#
# Pipeline:
#
#     synchronized gait phase
#             +
#     nominal phase time
#             +
#     future support plan
#             +
#     nominal current CoM
#
#             ↓
#
#     nominal DCM horizon
#
#             ↓
#
#     nominal CoM horizon
#
#
# Output:
#
#     xi_ref
#     xi_dot_ref
#
#     p_CoM_ref
#     v_CoM_ref
#
#
# IMPORTANT:
#
# This function does NOT:
#
#     - read MuJoCo state
#     - process actual contact
#     - modify footholds
#     - generate attitude reference
#     - build 13D SRBD X_ref
#     - solve MPC / QP
#
# Those belong to other layers.
# ============================================================

def build_mpc_translational_reference(
    current_phase,
    t_phase,
    timing,
    support_points,
    W_p_CoM_nominal_current,
    com_height=None,
    gravity=DEFAULT_GRAVITY,
    horizon=None,
    dt_mpc=None,
    alpha_ds_ini=DEFAULT_ALPHA_DS_INI,
    W_xi_terminal_xy=None
):
    """
    Build the flat-ground translational reference package
    for SRBD-MPC.

    Parameters
    ----------
    current_phase : str

        Current synchronized nominal gait phase.

        Expected examples:

            "LSS"
            "DS_L_TO_R"
            "RSS"
            "DS_R_TO_L"


    t_phase : float

        Current time inside the synchronized gait phase.


    timing : dict

        Gait timing generated by:

            Command/gait_timing.py


    support_points : array_like, shape (M,2) or (M,3)

        Ordered future support sequence.

        Example starting from LSS:

            [
                L0,
                R1,
                L2,
                R3,
                ...
            ]


    W_p_CoM_nominal_current : array_like, shape (3,)

        Current NOMINAL CoM position.

        IMPORTANT:

            This is not the measured actual CoM.

        The nominal current state is maintained by the
        reference-generation layer.


    com_height : float or None

        Constant CoM height used by the flat-ground
        DCM/LIPM reference model.

        If None:

            com_height =
                W_p_CoM_nominal_current[2]


    gravity : float

        Gravity magnitude.


    horizon : int or None

        MPC prediction horizon.

        If None:

            timing["horizon"]


    dt_mpc : float or None

        MPC prediction-grid interval.

        If None:

            timing["dt_mpc"]


    alpha_ds_ini : float

        Fraction of DS duration before the preliminary
        instantaneous support transition.

        Default:

            0.5


    W_xi_terminal_xy : array_like, shape (2,), or None

        Optional terminal DCM condition.

        If None:

            final support point is used.


    Returns
    -------
    reference : dict

        reference["omega0"]

        reference["com_height"]

        reference["sample_times"]

        reference["W_xi_nominal_current_xy"]

        reference["W_xi_dot_nominal_current_xy"]

        reference["W_xi_ref"]

        reference["W_xi_dot_ref"]

        reference["W_p_CoM_nominal_current"]

        reference["W_v_CoM_nominal_current"]

        reference["W_p_CoM_ref"]

        reference["W_v_CoM_ref"]

        reference["phase_sequence"]

        reference["segment_kind_sequence"]

        reference["horizon"]

        reference["dt_mpc"]

        reference["dcm"]

        reference["com"]
    """

    # ========================================================
    # 1. NOMINAL CURRENT CoM
    # ========================================================

    W_p_CoM_nominal_current = _validate_vector(
        W_p_CoM_nominal_current,
        "W_p_CoM_nominal_current",
        3
    )


    # ========================================================
    # 2. FLAT-GROUND HEIGHT
    # ========================================================

    if com_height is None:

        com_height = float(
            W_p_CoM_nominal_current[
                2
            ]
        )


    com_height = _validate_positive_scalar(
        com_height,
        "com_height"
    )


    # --------------------------------------------------------
    # The nominal CoM state and DCM model must use exactly
    # the same constant height.
    # --------------------------------------------------------

    if not np.isclose(
        W_p_CoM_nominal_current[
            2
        ],
        com_height,
        atol=1e-10,
        rtol=0.0
    ):

        raise ValueError(
            "W_p_CoM_nominal_current[2] phải bằng "
            "com_height."
        )


    # ========================================================
    # 3. GRAVITY
    # ========================================================

    gravity = _validate_positive_scalar(
        gravity,
        "gravity"
    )


    # ========================================================
    # 4. DCM NATURAL FREQUENCY
    #
    #     omega0 = sqrt(g / z0)
    # ========================================================

    omega0 = compute_omega0(

        com_height=com_height,

        gravity=gravity
    )


    # ========================================================
    # 5. BUILD NOMINAL DCM HORIZON
    # ========================================================

    dcm = build_dcm_reference_horizon(

        current_phase=current_phase,

        t_phase=t_phase,

        timing=timing,

        support_points=support_points,

        omega0=omega0,

        horizon=horizon,

        dt_mpc=dt_mpc,

        alpha_ds_ini=alpha_ds_ini,

        W_xi_terminal_xy=(
            W_xi_terminal_xy
        )
    )


    # ========================================================
    # 6. BUILD NOMINAL CoM HORIZON
    #
    # IMPORTANT:
    #
    # Use the NOMINAL DCM at current time generated from the
    # support plan.
    #
    # Do not use actual measured DCM here.
    # ========================================================

    com = build_com_reference_from_dcm(

        W_p_CoM_nominal_current=(
            W_p_CoM_nominal_current
        ),

        W_xi_nominal_current_xy=(
            dcm[
                "W_xi_nominal_current_xy"
            ]
        ),

        W_xi_ref=(
            dcm[
                "W_xi_ref"
            ]
        ),

        omega0=omega0,

        dt_mpc=(
            dcm[
                "dt_mpc"
            ]
        ),

        com_height=com_height
    )


    # ========================================================
    # 7. CONSISTENCY CHECK
    # ========================================================

    if (
        dcm[
            "W_xi_ref"
        ].shape[
            0
        ]
        !=
        com[
            "W_p_CoM_ref"
        ].shape[
            0
        ]
    ):

        raise RuntimeError(
            "DCM và CoM reference không cùng horizon."
        )


    if not np.isclose(
        dcm[
            "dt_mpc"
        ],
        com[
            "dt_mpc"
        ],
        atol=1e-12,
        rtol=0.0
    ):

        raise RuntimeError(
            "DCM và CoM reference không cùng dt_mpc."
        )


    # ========================================================
    # 8. BUILD SYNCHRONIZED REFERENCE PACKAGE
    # ========================================================

    reference = {
        # ----------------------------------------------------
        # Flat-ground model parameters
        # ----------------------------------------------------

        "omega0":
            omega0,

        "com_height":
            com_height,


        # ----------------------------------------------------
        # MPC timing
        # ----------------------------------------------------

        "horizon":
            dcm[
                "horizon"
            ],

        "dt_mpc":
            dcm[
                "dt_mpc"
            ],

        "sample_times":
            dcm[
                "sample_times"
            ].copy(),


        # ----------------------------------------------------
        # Current nominal DCM state
        # ----------------------------------------------------

        "W_xi_nominal_current_xy":
            dcm[
                "W_xi_nominal_current_xy"
            ].copy(),

        "W_xi_dot_nominal_current_xy":
            dcm[
                "W_xi_dot_nominal_current_xy"
            ].copy(),


        # ----------------------------------------------------
        # Future DCM reference
        #
        # k+1 ... k+N
        # ----------------------------------------------------

        "W_xi_ref":
            dcm[
                "W_xi_ref"
            ].copy(),

        "W_xi_dot_ref":
            dcm[
                "W_xi_dot_ref"
            ].copy(),


        # ----------------------------------------------------
        # Current nominal CoM state
        # ----------------------------------------------------

        "W_p_CoM_nominal_current":
            com[
                "W_p_CoM_nominal_current"
            ].copy(),

        "W_v_CoM_nominal_current":
            com[
                "W_v_CoM_nominal_current"
            ].copy(),


        # ----------------------------------------------------
        # Future CoM reference
        #
        # k+1 ... k+N
        # ----------------------------------------------------

        "W_p_CoM_ref":
            com[
                "W_p_CoM_ref"
            ].copy(),

        "W_v_CoM_ref":
            com[
                "W_v_CoM_ref"
            ].copy(),


        # ----------------------------------------------------
        # Gait / trajectory diagnostics
        # ----------------------------------------------------

        "phase_sequence":
            dcm[
                "phase_sequence"
            ],

        "segment_kind_sequence":
            dcm[
                "segment_kind_sequence"
            ],


        # ----------------------------------------------------
        # Complete lower-level diagnostics
        # ----------------------------------------------------

        "dcm":
            dcm,

        "com":
            com,
    }


    return reference