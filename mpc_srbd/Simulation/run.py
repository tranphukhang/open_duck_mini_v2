def validate_multiple(
    larger_dt,
    smaller_dt,
    name
):

    steps = int(
        round(
            larger_dt
            /
            smaller_dt
        )
    )

    if steps <= 0:

        raise ValueError(
            f"{name}: số step phải > 0."
        )

    if not np.isclose(
        steps
        *
        smaller_dt,
        larger_dt,
        atol=1e-12
    ):

        raise ValueError(
            f"{name}: timing không phải bội số nguyên."
        )

    return steps


