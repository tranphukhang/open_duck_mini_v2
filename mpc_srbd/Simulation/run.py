# ============================================================
# EXACT LIPM PROPAGATION
# ============================================================

def lipm_exact_step(
    c_xy,
    v_xy,
    p_support_xy,
    omega,
    dt
):

    c_xy = np.asarray(
        c_xy,
        dtype=float
    ).reshape(
        2
    )

    v_xy = np.asarray(
        v_xy,
        dtype=float
    ).reshape(
        2
    )

    p_support_xy = np.asarray(
        p_support_xy,
        dtype=float
    ).reshape(
        2
    )

    C = np.cosh(
        omega
        *
        dt
    )

    S = np.sinh(
        omega
        *
        dt
    )

    r = (
        c_xy
        -
        p_support_xy
    )

    c_next = (
        p_support_xy
        +
        r
        *
        C
        +
        v_xy
        /
        omega
        *
        S
    )

    v_next = (
        r
        *
        omega
        *
        S
        +
        v_xy
        *
        C
    )

    return (
        c_next,
        v_next
    )


def compute_dcm(
    c_xy,
    v_xy,
    omega
):

    return (
        np.asarray(
            c_xy,
            dtype=float
        ).reshape(
            2
        )
        +
        np.asarray(
            v_xy,
            dtype=float
        ).reshape(
            2
        )
        /
        omega
    )


# ============================================================
# PERIODIC DCM OFFSET
#
# side:
#
#   +1 = left touchdown
#   -1 = right touchdown
# ============================================================

def periodic_dcm_offset(
    omega,
    T_step,
    v_cmd,
    foot_width,
    side
):

    E = np.exp(
        omega
        *
        T_step
    )

    return np.array(
        [
            (
                v_cmd[
                    0
                ]
                *
                T_step
                /
                (
                    E
                    -
                    1.0
                )
            ),

            (
                v_cmd[
                    1
                ]
                *
                T_step
                /
                (
                    E
                    -
                    1.0
                )
                -
                side
                *
                foot_width
                /
                (
                    E
                    +
                    1.0
                )
            )
        ],
        dtype=float
    )


# ============================================================
# DCM FOOTHOLD FROM CURRENT STATE
#
# The target is computed for RIGHT touchdown:
#
#   side = -1
#
# First predict the touchdown DCM under the LEFT stance foot,
# then:
#
#   p_R_target = xi_touchdown - b_R
# ============================================================

def compute_right_dcm_foothold(
    c_xy,
    v_xy,
    p_left_xy,
    right_initial,
    omega,
    remaining_time,
    foot_width
):

    remaining_time = max(
        float(
            remaining_time
        ),
        0.0
    )

    (
        c_td,
        v_td

    ) = lipm_exact_step(

        c_xy=(
            c_xy
        ),

        v_xy=(
            v_xy
        ),

        p_support_xy=(
            p_left_xy
        ),

        omega=(
            omega
        ),

        dt=(
            remaining_time
        )
    )

    xi_td = compute_dcm(
        c_td,
        v_td,
        omega
    )

    b_right = periodic_dcm_offset(

        omega=(
            omega
        ),

        T_step=(
            T_STEP
        ),

        v_cmd=(
            V_CMD
        ),

        foot_width=(
            foot_width
        ),

        side=-1
    )

    raw_xy = (
        xi_td
        -
        b_right
    )

    right_initial = np.asarray(
        right_initial,
        dtype=float
    ).reshape(
        3
    )

    clipped_xy = raw_xy.copy()

    clipped_xy[
        0
    ] = np.clip(

        clipped_xy[
            0
        ],

        right_initial[
            0
        ]
        -
        FOOTHOLD_BACKWARD_LIMIT,

        right_initial[
            0
        ]
        +
        FOOTHOLD_FORWARD_LIMIT
    )

    clipped_xy[
        1
    ] = np.clip(

        clipped_xy[
            1
        ],

        right_initial[
            1
        ]
        -
        FOOTHOLD_LATERAL_LIMIT,

        right_initial[
            1
        ]
        +
        FOOTHOLD_LATERAL_LIMIT
    )

    target = np.array(
        [
            clipped_xy[
                0
            ],

            clipped_xy[
                1
            ],

            right_initial[
                2
            ]
        ],
        dtype=float
    )

    raw_target = np.array(
        [
            raw_xy[
                0
            ],

            raw_xy[
                1
            ],

            right_initial[
                2
            ]
        ],
        dtype=float
    )

    return (
        target,
        raw_target,
        c_td,
        v_td,
        xi_td,
        b_right
    )


# ============================================================
# QUINTIC SEGMENT
#
# Boundary conditions:
#
#   p(0)   = p0
#   v(0)   = v0
#   a(0)   = a0
#
#   p(T)   = pf
#   v(T)   = vf
#   a(T)   = af
#
# Used for:
#
#   1. DS weight transfer
#   2. post-touchdown stopping
# ============================================================

class QuinticSegment:

    def __init__(
        self,
        p0,
        v0,
        a0,
        pf,
        vf,
        af,
        duration
    ):

        self.p0 = np.asarray(
            p0,
            dtype=float
        ).reshape(
            -1
        )

        self.v0 = np.asarray(
            v0,
            dtype=float
        ).reshape(
            -1
        )

        self.a0 = np.asarray(
            a0,
            dtype=float
        ).reshape(
            -1
        )

        self.pf = np.asarray(
            pf,
            dtype=float
        ).reshape(
            -1
        )

        self.vf = np.asarray(
            vf,
            dtype=float
        ).reshape(
            -1
        )

        self.af = np.asarray(
            af,
            dtype=float
        ).reshape(
            -1
        )

        self.duration = float(
            duration
        )

        n = (
            self.p0.size
        )

        for value in (
            self.v0,
            self.a0,
            self.pf,
            self.vf,
            self.af
        ):

            if value.size != n:

                raise ValueError(
                    "QuinticSegment: dimension mismatch."
                )

        T = (
            self.duration
        )

        if T <= 0.0:

            raise ValueError(
                "QuinticSegment duration phải > 0."
            )

        self.coeff = np.zeros(
            (
                n,
                6
            ),
            dtype=float
        )

        self.coeff[
            :,
            0
        ] = (
            self.p0
        )

        self.coeff[
            :,
            1
        ] = (
            self.v0
        )

        self.coeff[
            :,
            2
        ] = (
            0.5
            *
            self.a0
        )

        A = np.array(
            [
                [
                    T**3,
                    T**4,
                    T**5
                ],
                [
                    3.0
                    *
                    T**2,
                    4.0
                    *
                    T**3,
                    5.0
                    *
                    T**4
                ],
                [
                    6.0
                    *
                    T,
                    12.0
                    *
                    T**2,
                    20.0
                    *
                    T**3
                ]
            ],
            dtype=float
        )

        for i in range(
            n
        ):

            a0_i = (
                self.coeff[
                    i,
                    0
                ]
            )

            a1_i = (
                self.coeff[
                    i,
                    1
                ]
            )

            a2_i = (
                self.coeff[
                    i,
                    2
                ]
            )

            rhs = np.array(
                [
                    (
                        self.pf[
                            i
                        ]
                        -
                        (
                            a0_i
                            +
                            a1_i
                            *
                            T
                            +
                            a2_i
                            *
                            T**2
                        )
                    ),

                    (
                        self.vf[
                            i
                        ]
                        -
                        (
                            a1_i
                            +
                            2.0
                            *
                            a2_i
                            *
                            T
                        )
                    ),

                    (
                        self.af[
                            i
                        ]
                        -
                        (
                            2.0
                            *
                            a2_i
                        )
                    )
                ],
                dtype=float
            )

            self.coeff[
                i,
                3:6
            ] = np.linalg.solve(
                A,
                rhs
            )


    def evaluate(
        self,
        t
    ):

        t = float(
            np.clip(
                t,
                0.0,
                self.duration
            )
        )

        p = np.zeros(
            self.p0.size,
            dtype=float
        )

        v = np.zeros_like(
            p
        )

        a = np.zeros_like(
            p
        )

        for i in range(
            self.p0.size
        ):

            c = (
                self.coeff[
                    i
                ]
            )

            p[
                i
            ] = (
                c[
                    0
                ]
                +
                c[
                    1
                ]
                *
                t
                +
                c[
                    2
                ]
                *
                t**2
                +
                c[
                    3
                ]
                *
                t**3
                +
                c[
                    4
                ]
                *
                t**4
                +
                c[
                    5
                ]
                *
                t**5
            )

            v[
                i
            ] = (
                c[
                    1
                ]
                +
                2.0
                *
                c[
                    2
                ]
                *
                t
                +
                3.0
                *
                c[
                    3
                ]
                *
                t**2
                +
                4.0
                *
                c[
                    4
                ]
                *
                t**3
                +
                5.0
                *
                c[
                    5
                ]
                *
                t**4
            )

            a[
                i
            ] = (
                2.0
                *
                c[
                    2
                ]
                +
                6.0
                *
                c[
                    3
                ]
                *
                t
                +
                12.0
                *
                c[
                    4
                ]
                *
                t**2
                +
                20.0
                *
                c[
                    5
                ]
                *
                t**3
            )

        return (
            p,
            v,
            a
        )


