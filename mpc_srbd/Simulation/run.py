    # ========================================================
    # UPDATE PHASE MACHINE
    # ========================================================

    def update_phase(
        self,
        current_time,
        current_state,
        left_foot,
        right_foot
    ):

        t = float(
            current_time
        )

        current_state = np.asarray(
            current_state,
            dtype=float
        ).reshape(
            13
        )

        if (
            self.phase
            ==
            PHASE_STAND
        ):

            if t >= SETTLE_DURATION:

                self.start_transfer(

                    current_time=(
                        t
                    ),

                    current_state=(
                        current_state
                    ),

                    left_foot=(
                        left_foot
                    ),

                    right_foot=(
                        right_foot
                    )
                )

            return


        if (
            self.phase
            ==
            PHASE_TRANSFER
        ):

            transfer_elapsed = (

                t

                -

                self.transfer_start_time
            )

            transfer_finished = (
                transfer_elapsed
                >=
                TRANSFER_DURATION
            )

            y_error = (

                current_state[
                    1
                ]

                -

                self.y_liftoff_des
            )

            vy = (
                current_state[
                    7
                ]
            )

            xi_y_actual = (

                current_state[
                    1
                ]

                +

                vy

                /

                self.omega
            )

            dcm_y_error = (

                xi_y_actual

                -

                self.xi_liftoff_y_des
            )

            ready = (
                transfer_finished
                and
                abs(
                    y_error
                )
                <=
                TRANSFER_Y_TOL
                and
                abs(
                    dcm_y_error
                )
                <=
                TRANSFER_DCM_TOL
            )

            if ready:

                self.start_lss(

                    current_time=(
                        t
                    ),

                    current_state=(
                        current_state
                    ),

                    left_foot=(
                        left_foot
                    ),

                    right_foot=(
                        right_foot
                    )
                )

                return

            if (
                transfer_elapsed
                >
                (
                    TRANSFER_DURATION
                    +
                    MAX_TRANSFER_HOLD
                )
            ):

                raise RuntimeError(

                    "\nWeight transfer timeout.\n"
                    f"CoM y = {current_state[1]:.6f}\n"
                    f"target y = {self.y_liftoff_des:.6f}\n"
                    f"error y = {y_error:.6f}\n"
                    f"vy = {vy:.6f}\n"
                    f"xi_y actual = {xi_y_actual:.6f}\n"
                    f"xi_y target = {self.xi_liftoff_y_des:.6f}\n"
                    f"DCM y error = {dcm_y_error:.6f}\n"
                    "Không chuyển sang single support để tránh robot ngã."
                )

            return


        if (
            self.phase
            ==
            PHASE_LSS
        ):

            self.update_swing_foothold(
                current_time=(
                    t
                ),
                current_state=(
                    current_state
                )
            )

            if t < self.planned_touchdown_time:

                return

            right_foot = np.asarray(
                right_foot,
                dtype=float
            ).reshape(
                3
            )

            foothold = np.asarray(
                _SHARED_FOOTHOLD[
                    "value"
                ],
                dtype=float
            ).reshape(
                3
            )

            touchdown_error = float(
                np.linalg.norm(
                    right_foot
                    -
                    foothold
                )
            )

            close_enough = (
                touchdown_error
                <=
                TOUCHDOWN_POSITION_TOL
            )

            grace_expired = (
                t
                >=
                (
                    self.planned_touchdown_time
                    +
                    TOUCHDOWN_GRACE
                )
            )

            if (
                close_enough
                or
                grace_expired
            ):

                self.start_post_ds(

                    current_time=(
                        t
                    ),

                    current_state=(
                        current_state
                    ),

                    left_foot=(
                        left_foot
                    ),

                    right_foot=(
                        right_foot
                    )
                )

            return


        if (
            self.phase
            ==
            PHASE_POST_DS
        ):

            if (
                t
                >=
                (
                    self.post_start_time
                    +
                    POST_DS_DURATION
                )
            ):

                self.phase = (
                    PHASE_DONE
                )

                print(
                    "\n"
                    +
                    "=" * 92
                )

                print(
                    "ONE STEP COMPLETED"
                )

                print(
                    "=" * 92
                )

            return


    # ========================================================
    # REFERENCE AT ABSOLUTE TIME
    # ========================================================

    def evaluate_reference(
        self,
        t
    ):

        t = float(
            t
        )

        # ----------------------------------------------------
        # Before transfer is initialized
        # ----------------------------------------------------

        if self.transfer_segment is None:

            p = (
                self.initial_state[
                    0:3
                ].copy()
            )

            v = np.zeros(
                3,
                dtype=float
            )

            return (
                p,
                v
            )

        # ----------------------------------------------------
        # DS weight transfer
        # ----------------------------------------------------

        if (
            self.liftoff_time is None
            or
            t
            <
            self.liftoff_time
        ):

            tau = (

                t

                -

                self.transfer_start_time
            )

            if tau <= 0.0:

                p = (
                    self.transfer_segment.p0.copy()
                )

                v = (
                    self.transfer_segment.v0.copy()
                )

            elif tau < TRANSFER_DURATION:

                (
                    p,
                    v,
                    _

                ) = self.transfer_segment.evaluate(
                    tau
                )

            else:

                (
                    p,
                    v,
                    _

                ) = self.transfer_segment.evaluate(
                    TRANSFER_DURATION
                )

            return (
                p,
                v
            )

        # ----------------------------------------------------
        # LSS / swing
        # ----------------------------------------------------

        if (
            self.post_start_time is None
            and
            (
                self.phase
                ==
                PHASE_LSS
                or
                t
                <=
                (
                    self.planned_touchdown_time
                    +
                    TOUCHDOWN_GRACE
                )
            )
        ):

            tau = max(

                t

                -

                self.liftoff_time,

                0.0
            )

            (
                c_xy,
                v_xy

            ) = lipm_exact_step(

                c_xy=(
                    self.ss_c0
                ),

                v_xy=(
                    self.ss_v0
                ),

                p_support_xy=(
                    self.ss_left_support
                ),

                omega=(
                    self.omega
                ),

                dt=(
                    tau
                )
            )

            p = np.array(
                [
                    c_xy[
                        0
                    ],
                    c_xy[
                        1
                    ],
                    self.transfer_segment.pf[
                        2
                    ]
                ],
                dtype=float
            )

            v = np.array(
                [
                    v_xy[
                        0
                    ],
                    v_xy[
                        1
                    ],
                    0.0
                ],
                dtype=float
            )

            return (
                p,
                v
            )

        # ----------------------------------------------------
        # Post touchdown
        # ----------------------------------------------------

        if self.post_segment is not None:

            tau = (

                t

                -

                self.post_start_time
            )

            if tau < POST_DS_DURATION:

                (
                    p,
                    v,
                    _

                ) = self.post_segment.evaluate(
                    tau
                )

            else:

                p = (
                    self.post_segment.pf.copy()
                )

                v = np.zeros(
                    3,
                    dtype=float
                )

            return (
                p,
                v
            )

        # ----------------------------------------------------
        # Fallback
        # ----------------------------------------------------

        p = (
            self.transfer_segment.pf.copy()
        )

        v = np.zeros(
            3,
            dtype=float
        )

        return (
            p,
            v
        )


    # ========================================================
    # MPC REFERENCE HORIZON
    # ========================================================

    def generate_X_ref(
        self,
        current_time
    ):

        X = np.zeros(
            (
                N,
                13
            ),
            dtype=float
        )

        for k in range(
            N
        ):

            t_pred = (

                current_time

                +

                (
                    k
                    +
                    1
                )
                *
                dt_mpc
            )

            (
                p_ref,
                v_ref

            ) = self.evaluate_reference(
                t_pred
            )

            x_ref = np.zeros(
                13,
                dtype=float
            )

            x_ref[
                0:3
            ] = (
                p_ref
            )

            x_ref[
                3
            ] = 0.0

            x_ref[
                4
            ] = 0.0

            x_ref[
                5
            ] = (
                self.yaw_ref
            )

            x_ref[
                6:9
            ] = (
                v_ref
            )

            x_ref[
                9:12
            ] = 0.0

            x_ref[
                12
            ] = 1.0

            X[
                k
            ] = (
                x_ref
            )

        return (
            X.reshape(
                N
                *
                13
            ),
            X
        )


    # ========================================================
    # CONTACT SCHEDULE OVER MPC HORIZON
    # ========================================================

    def build_contact_schedule(
        self,
        current_time
    ):

        schedule = np.zeros(
            (
                N,
                2
            ),
            dtype=int
        )

        for k in range(
            N
        ):

            t_pred = (

                current_time

                +

                (
                    k
                    +
                    1
                )
                *
                dt_mpc
            )

            if (
                self.phase
                ==
                PHASE_TRANSFER
            ):

                # ------------------------------------------------
                # Preview the upcoming LSS BEFORE actual liftoff.
                #
                # This is essential for load transfer:
                #
                #     DS now
                #       ->
                #     future LSS inside MPC horizon
                #
                # so MPC starts unloading the right foot instead
                # of carrying right-foot wrench until the exact
                # liftoff instant.
                # ------------------------------------------------

                if (
                    self.planned_liftoff_time
                    is not None
                    and
                    t_pred
                    >=
                    self.planned_liftoff_time
                ):

                    schedule[
                        k
                    ] = (
                        LEFT_SINGLE_SUPPORT
                    )

                else:

                    schedule[
                        k
                    ] = (
                        DOUBLE_SUPPORT
                    )

            elif (
                self.phase
                ==
                PHASE_LSS
            ):

                # During the planned swing and optional small
                # touchdown grace, keep the right foot disabled.
                if (
                    t_pred
                    <
                    (
                        self.planned_touchdown_time
                        +
                        TOUCHDOWN_GRACE
                    )
                ):

                    schedule[
                        k
                    ] = (
                        LEFT_SINGLE_SUPPORT
                    )

                else:

                    schedule[
                        k
                    ] = (
                        DOUBLE_SUPPORT
                    )

            else:

                schedule[
                    k
                ] = (
                    DOUBLE_SUPPORT
                )

        return schedule


