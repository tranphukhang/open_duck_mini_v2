clc;
clear;
close all;

script_dir = fileparts(mfilename('fullpath'));

wrench_file = fullfile(script_dir, '..', 'matlab', 'data', ...
    'wrench_distance.csv');

data = readtable(wrench_file);

t = data.time_s;
d_raw = data.distance;

%% ============================================================
% OUTLIER REMOVAL
% ============================================================

window_size = 101;

outlier_mask = isoutlier( ...
    d_raw, ...
    'movmedian', ...
    window_size, ...
    'ThresholdFactor', ...
    3);

d = d_raw;

if any(outlier_mask)

    d(outlier_mask) = interp1( ...
        t(~outlier_mask), ...
        d_raw(~outlier_mask), ...
        t(outlier_mask), ...
        'linear', ...
        'extrap');

end

fprintf('Number of detected outliers: %d\n', ...
    sum(outlier_mask));

%% ============================================================
% PLOT
% ============================================================

figure('Color', 'w');

plot(t, d, 'r-', ...
    'LineWidth', 1.5, ...
    'DisplayName', 'd');

xlabel('Time (s)', ...
    'FontSize', 12, ...
    'FontName', 'Times New Roman');

ylabel('Amplitude', ...
    'FontSize', 12, ...
    'FontName', 'Times New Roman');

title('Distance to the feasible contact-wrench cone', ...
    'FontSize', 13, ...
    'FontName', 'Times New Roman', ...
    'FontWeight', 'normal');

legend('Location', 'best', ...
    'Interpreter', 'latex', ...
    'FontSize', 11);

grid on;
box on;

set(gca, ...
    'FontSize', 11, ...
    'LineWidth', 1.0, ...
    'FontName', 'Times New Roman');

xlim([t(1) t(end)]);
ylim([0 4e-13]);